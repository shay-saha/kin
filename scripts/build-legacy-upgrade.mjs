// Builds a single transactional SQL-editor upgrade. This script never contacts a database.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = new URL('../', import.meta.url);
const read = name => readFile(new URL(`supabase/migrations/${name}`, root), 'utf8');
const body = sql => sql.replace(/^begin;\s*$/gm, '').replace(/^commit;\s*$/gm, '').trim();
export async function buildLegacyUpgrade() {
  const names = ['002_atomic_ingestion.sql', '003_family_boundary_and_weaver.sql', '004_wearer_membership.sql',
    '006_explicit_api_grants.sql', '007_self_contribution.sql', '008_living_stories.sql',
    '009_family_accounts.sql', '010_loved_one_invites.sql', '011_rust_face_models.sql'];
  const sections = [];
  for (const name of names) {
    let sql = body(await read(name));
    sql = sql.replace(/add column (?!if not exists)/g, 'add column if not exists ')
      .replace(/create table (?!if not exists)/g, 'create table if not exists ')
      .replace(/create function /g, 'create or replace function ')
      .replace(/create unique index (?!if not exists)/g, 'create unique index if not exists ');
    // Replace only named policies owned by these migrations. Existing account
    // policies are retained; all changes commit together with descriptor revokes.
    sql = sql.replace(/^create policy (\w+) on ([\w.]+)/gm,
      (_, policy, table) => `drop policy if exists ${policy} on ${table};\ncreate policy ${policy} on ${table}`);
    sql = sql.replace("execute format('create policy family_read on", "execute format('drop policy if exists family_read on public.%I', t);\n    execute format('create policy family_read on");
    sql = sql.replace(/drop policy (?!if exists)/g, 'drop policy if exists ');
    // Never delete duplicate legacy questions. Abort before changing anything;
    // an operator can decide which records to retain if this state exists.
    sql = sql.replace(/delete from public\.weaver_questions older using public\.weaver_questions newer[\s\S]*?;\n/, '');
    if (name === '008_living_stories.sql') sql = sql.replace('create trigger sync_memory_audio_segments',
      'drop trigger if exists sync_memory_audio_segments on public.memories;\ncreate trigger sync_memory_audio_segments');
    sections.push(`-- From ${name}\n${sql}`);
  }
  return `-- Upgrade the original pull-apart branch database to the merged main schema.
-- Generated by: node scripts/build-legacy-upgrade.mjs
-- Run this ENTIRE file in Supabase SQL Editor. No account/media/memory reset.
-- Includes the equivalent of main 002–004 and 006–011. Deliberately skips
-- 005_consolidate_hackmit_demo: a demo-data rewrite is not a schema upgrade.
-- Safe to retry: one transaction; existing rows/IDs are retained.
-- Legacy memories/faces are NOT automatically relabeled as verified evidence.
begin;

do $$ begin
  if to_regclass('public.family_members') is null then
    raise exception 'This upgrade requires the original family account schema. For a new database, use the numbered migrations.';
  end if;
  if exists(select 1 from public.weaver_questions where status='open' and gap_node_id is not null
    group by family_id,gap_node_id,gap_type having count(*)>1)
    or exists(select 1 from public.memories where kind='answer' and source_question_id is not null
      group by source_question_id having count(*)>1) then
    raise exception 'Duplicate question/answer records need review before upgrading. Nothing was changed.';
  end if;
end $$;

${sections.join('\n\n')}

-- Existing branch memberships predate the INSERT trigger in 010. Bridge them
-- too, without recreating accounts, changing IDs, or touching their passwords.
do $$ begin
  if exists(select 1 from public.family_members m join public.wearer_accounts w on w.user_id=m.user_id
    where m.role='loved_one' and m.family_id<>w.family_id) then
    raise exception 'Conflicting wearer membership needs review. Nothing was changed.';
  end if;
end $$;
insert into public.wearer_accounts(user_id,family_id)
select user_id,family_id from public.family_members where role='loved_one'
on conflict(user_id) do nothing;
insert into public.relatives(family_id,name,relation_to_wearer,color,is_self,self_capture_open)
select w.family_id,w.name,'self','#6958C9',true,false from public.wearer w
where exists(select 1 from public.wearer_accounts a where a.family_id=w.family_id)
  and not exists(select 1 from public.relatives r where r.family_id=w.family_id and r.is_self);
update auth.users u set raw_app_meta_data=coalesce(u.raw_app_meta_data,'{}'::jsonb) || jsonb_build_object(
  'kin_family_id',m.family_id,'kin_contributor_id',m.relative_id,
  'kin_role',case when m.role='loved_one' then 'wearer' else 'contributor' end,
  'kin_admin',m.role='contributor' and exists(select 1 from public.families f where f.id=m.family_id and f.owner_id=u.id)
) from public.family_members m where m.user_id=u.id;
-- The old branch granted a face-descriptor RPC to browsers. Its implementation
-- remains for historical compatibility, but only server access is permitted.
do $$ begin
  if to_regprocedure('public.match_keeper_faces(vector,text,uuid,integer)') is not null then
    revoke all on function public.match_keeper_faces(vector,text,uuid,integer) from public,anon,authenticated;
    grant execute on function public.match_keeper_faces(vector,text,uuid,integer) to service_role;
  end if;
end $$;
notify pgrst, 'reload schema';
commit;
`;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(new URL('supabase/upgrades/pull_apart_to_main.sql', root), await buildLegacyUpgrade());
  console.log('Wrote supabase/upgrades/pull_apart_to_main.sql (no database connection).');
}
